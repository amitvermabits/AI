
"""
AI Travel Buddy - Claude Tool Execution Lab.

Certification:
    CCDV-F | Domain 1 | Skill 1.1 - Agent Architecture

Learning objectives:
    1. Receive a tool_use request from Claude.
    2. Map the tool name to a real Python function.
    3. Execute the function with Claude's arguments.
    4. Send its output back as a tool_result.
    5. Observe Claude's next decision.

Scope:
    This lab executes ONE tool and makes ONE
    follow-up API request.

    A later lab will implement the complete
    multi-step agent loop.

Run:
    uv run python -m app.agents.tool_execution_lab
"""

import json
import os
from typing import Any

from anthropic import Anthropic
from dotenv import load_dotenv

from app.agents.tool_selection_lab import (
    get_tool_definitions,
)

from app.tools.transport import (
    search_trains,
    search_buses,
)


# Only these approved functions may be called by Claude.
#
# This is a tool registry: a mapping between the
# public tool name and its Python implementation.
TOOL_REGISTRY = {
    "search_trains": search_trains,
    "search_buses": search_buses,
}


def execute_tool(
    tool_name: str,
    tool_input: dict[str, Any],
) -> dict:
    """
    Execute one approved Python tool.

    Args:
        tool_name:
            Name returned by Claude's tool_use block.

        tool_input:
            Arguments generated by Claude,
            for example:
            {
                "from_city": "Toulouse",
                "to_city": "Paris"
            }

    Returns:
        Transport search result or an error dictionary.

    Security:
        Never execute arbitrary function names,
        code or shell commands from model output.
        Use the approved TOOL_REGISTRY only.
    """

    function = TOOL_REGISTRY.get(tool_name)

    if function is None:
        return {"error": f"Unknown tool: {tool_name}"}

    try:
        # ** expands the dictionary into keyword arguments.
        #
        # Example:
        # search_trains(
        #     from_city="Toulouse",
        #     to_city="Paris"
        # )
        return function(**tool_input)

    except (ValueError, TypeError) as error:
        # Invalid routes or malformed arguments should
        # be reported to Claude rather than fabricated.
        return {"error": str(error)}


def main() -> None:
    """
    Perform one complete Claude tool-use round trip.

    Flow:
        User -> Claude -> tool_use
             -> Python function -> tool_result
             -> Claude's next response

    The second response may be:
        - A final text response, or
        - Another tool_use request.

    This lab deliberately does not execute
    any second tool request.
    """

    # Load configuration from the project .env file.
    load_dotenv(override=True)

    if not os.getenv("ANTHROPIC_API_KEY"):
        raise RuntimeError("ANTHROPIC_API_KEY is missing")

    client = Anthropic()

    model = os.getenv(
        "CLAUDE_MODEL",
        "claude-haiku-5-5",
    )

    # Conversation history must be preserved.
    # Claude needs earlier messages to understand
    # which result belongs to which tool request.
    messages = [
        {
            "role": "user",
            "content": (
                "Find transport from Toulouse to Paris "
                "for less than 100 EUR. Prefer trains. "
                "Search transport options before recommending."
            ),
        }
    ]

    # STEP 1: Ask Claude to select a transport tool.
    response = client.messages.create(
        model=model,
        max_tokens=512,
        system=(
            "You are a travel planning assistant. "
            "Prefer trains when they meet the budget. "
            "If a searched train is too expensive, "
            "consider searching buses. "
            "Use tool results only; never invent prices."
        ),
        tools=get_tool_definitions(),
        tool_choice={
            "type": "any",
            "disable_parallel_tool_use": True,
        },
        messages=messages,
    )

    print("First stop reason:", response.stop_reason)

    for block in response.content:
        if block.type == "text":
            print("Claude says -1 :", block.text)

    # STEP 2: Identify Claude's requested tool.
    tool_blocks = [
        block
        for block in response.content
        if block.type == "tool_use"
    ]

    if len(tool_blocks) != 1:
        raise RuntimeError(
            "Expected exactly one tool_use block."
        )

    tool_request = tool_blocks[0]

    print("Claude selected:", tool_request.name)
    print("Arguments:", tool_request.input)

    # STEP 3: Our Python application runs the tool.
    tool_result = execute_tool(
        tool_request.name,
        tool_request.input,
    )

    print("Python tool result:", tool_result)

    # STEP 4: Add Claude's tool-use message
    # to the conversation history.
    messages.append({
        "role": "assistant",
        "content": response.content,
    })

    # STEP 5: Send the result back to Claude.
    #
    # tool_use_id associates this result with
    # the exact request Claude previously made.
    messages.append({
        "role": "user",
        "content": [
            {
                "type": "tool_result",
                "tool_use_id": tool_request.id,
                "content": json.dumps(tool_result),
                "is_error": "error" in tool_result,
            }
        ],
    })

    # STEP 6: Give Claude the observation and
    # allow it to decide its next action.
    #
    # auto allows either a response or another tool.
    # 'any' here would force another tool call.
    follow_up = client.messages.create(
        model=model,
        max_tokens=512,
        tools=get_tool_definitions(),
        tool_choice={
            "type": "auto",
            "disable_parallel_tool_use": True,
        },
        messages=messages,
    )

    print("Next stop reason:", follow_up.stop_reason)

    for block in follow_up.content:
        if block.type == "text":
            print("Claude says:", block.text)

        elif block.type == "tool_use":
            print("Claude next tool:", block.name)
            print("Next arguments:", block.input)
            print(
                "The second tool is not executed "
                "in this lab."
            )


if __name__ == "__main__":
    main()
